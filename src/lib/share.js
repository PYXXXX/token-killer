export function exportShareCard({
  story = 'activity',
  todayTokens = 0,
  totalTokens = 0,
  totalCost = 0,
  participantLabel = '燃烧者',
  globalRank = null,
  tier = null,
  locale = 'zh-CN',
  activity: suppliedActivity,
  achievement = null,
  achievements = null,
}) {
  const activity = suppliedActivity || buildTokenActivity([], { locale: localeTag(locale) })
  const canvas = document.createElement('canvas')
  canvas.width = 1600
  canvas.height = 900
  const ctx = canvas.getContext('2d')
  ctx.fillStyle = COLORS.background
  ctx.fillRect(0, 0, canvas.width, canvas.height)
  const data = {
    activity,
    todayTokens,
    totalTokens,
    totalCost,
    participantLabel,
    globalRank,
    tier,
    locale,
    achievement,
    achievements,
  }
  if (story === 'rank') drawRankStory(ctx, data)
  else if (story === 'achievement' && achievement) drawAchievementStory(ctx, data)
  else drawActivityStory(ctx, data)
  drawFooter(ctx, participantLabel, locale)

  const link = document.createElement('a')
  link.href = canvas.toDataURL('image/png')
  link.download = `token-killer-${story}-${new Date().toISOString().slice(0, 10)}.png`
  link.click()
}
