  ctx.textAlign = 'right'
  ctx.fillStyle = COLORS.text
  ctx.font = `600 18px ${MONO}`
  ctx.fillText(translateText(locale, participantLabel), 1512, 837)
  ctx.fillStyle = COLORS.muted
