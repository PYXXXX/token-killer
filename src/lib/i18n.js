export const SUPPORTED_LOCALES = ['zh-CN', 'en']

export function resolveLocale(preference = 'system') {
  if (preference === 'zh-CN' || preference === 'en') return preference
  const languages = globalThis.navigator?.languages || [globalThis.navigator?.language || '']
  return languages.some((language) => /^zh(?:-|$)/i.test(language)) ? 'zh-CN' : 'en'
}

export function localeTag(locale) {
  return locale === 'en' ? 'en-US' : 'zh-CN'
}

