export function translateText(locale, value) {
  if (locale !== 'en' || typeof value !== 'string' || !value) return value
  if (EN[value]) return EN[value]
  const rules = [
    [/^第 (\d+) 名$/, '#$1'],
    [/^第 (\d+) \/ (\d+) 页$/, 'Page $1 / $2'],
    [/^第 (\d+) 轮请求中，输出上限 (.+)$/, 'Round $1 in progress · output limit $2'],
    [/^第 (\d+) 轮完成，已回收 usage$/, 'Round $1 complete · usage received'],
    [/^第 (\d+) 轮（估算）$/, 'Round $1 (estimated)'],
    [/^第 (\d+) 轮$/, 'Round $1'],
    [/^(\d+) 次运行$/, '$1 runs'],
    [/^(\d+) 轮$/, '$1 rounds'],
    [/^(\d+) 秒$/, '$1 sec'],
    [/^(\d+) 分 (\d+) 秒$/, '$1 min $2 sec'],
    [/^燃烧者 #(\d+)$/, 'Burner #$1'],
  ]
  for (const [pattern, replacement] of rules) {
    if (pattern.test(value)) return value.replace(pattern, replacement)
  }
  let translated = value
  for (const [source, target] of PHRASES) {
    if (translated.includes(source)) translated = translated.split(source).join(target)
  }
  return translated
}

export function t(locale, zh, en) {
  return locale === 'en' ? en : zh
}
